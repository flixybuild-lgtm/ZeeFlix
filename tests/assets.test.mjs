/**
 * Guards the download / marketing surface. These are the files a stranger hits
 * first (the "Download APK" button, the installed PWA, the social preview), so
 * a broken link or a missing asset should fail CI rather than a visitor.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const exists = p => fs.existsSync(path.join(ROOT, p));

const INSTALL = 'public/install.html';
const APK_URL = 'https://github.com/flixybuild-lgtm/ZeeFlix/releases/latest/download/ZeeFlix-latest.apk';

test('install page exists, is self-contained HTML, and links the stable APK URL', () => {
  assert.ok(exists(INSTALL), 'public/install.html is missing');
  const html = read(INSTALL);
  assert.ok(html.startsWith('<!doctype html>'), 'install page needs a doctype');
  assert.ok(html.includes(APK_URL), 'install page must link the stable "latest" APK asset');
  assert.ok(html.includes('SHA256SUMS.txt'), 'install page should link the published checksums');
  // The release workflow uploads this exact filename.
  const workflow = read('.github/workflows/publish-assets.yml');
  assert.ok(workflow.includes('ZeeFlix-latest.apk'), 'release workflow must upload ZeeFlix-latest.apk');
});

test('every local asset referenced by the install page exists', () => {
  const html = read(INSTALL);
  const refs = [...html.matchAll(/(?:src|href)="([^"#:]+)"/g)].map(m => m[1]);
  const local = refs.filter(
    r => !r.startsWith('http') && !r.startsWith('//') && !r.startsWith('#') && !r.startsWith('mailto:')
  );
  assert.ok(local.length > 5, 'expected several local asset references');
  for (const ref of local) {
    const clean = ref.split('?')[0];
    // index.html is generated by the Rust build into dist/, so allow it.
    if (clean === 'index.html') continue;
    assert.ok(exists(path.join('public', clean)), `install page references missing file: ${clean}`);
  }
});

test('install page has SEO + social metadata and a scannable QR code', () => {
  const html = read(INSTALL);
  for (const needle of [
    '<meta name="description"',
    'property="og:title"',
    'property="og:description"',
    'property="og:image"',
    'name="twitter:card"',
    'rel="manifest"',
  ]) {
    assert.ok(html.includes(needle), `missing metadata: ${needle}`);
  }
  assert.ok(exists('public/install-qr.png'), 'install-qr.png should be generated by scripts/make_qr.py');
  const png = fs.readFileSync(path.join(ROOT, 'public/install-qr.png'));
  assert.equal(png.subarray(1, 4).toString(), 'PNG', 'QR code should be a real PNG');
});

test('the web app links to the install page from the shell and the footer', () => {
  const shell = read('templates/index.html');
  assert.ok(shell.includes('href="install.html"'), 'top bar / menu must link the install page');
  const footer = shell.slice(shell.indexOf('<footer'));
  assert.ok(footer.includes('install.html'), 'footer must link the install page');
});

test('download APK badge in the README points at a real release asset', () => {
  const readme = read('README.md');
  assert.ok(readme.includes(APK_URL), 'README download badge must use the stable APK URL');
  assert.ok(/docs\/marketing\/readme-hero\.png/.test(readme), 'README should use the generated hero strip');
  // Every screenshot the README embeds must exist in the repo.
  const shots = [...readme.matchAll(/src="(docs\/[^"]+\.png)"/g)].map(m => m[1]);
  assert.ok(shots.length >= 8, `expected the README to show the screenshot set, found ${shots.length}`);
  for (const shot of shots) assert.ok(exists(shot), `README references missing image: ${shot}`);
});

test('marketing assets are present and correctly sized for their platform', () => {
  const expectations = {
    'docs/marketing/social-card.png': [1280, 640],
    'docs/marketing/readme-hero.png': [1280, 400],
    'docs/marketing/feature-banner.png': [1600, 900],
  };
  for (const [file, [w, h]] of Object.entries(expectations)) {
    assert.ok(exists(file), `missing marketing asset: ${file}`);
    const buf = fs.readFileSync(path.join(ROOT, file));
    assert.equal(buf.subarray(1, 4).toString(), 'PNG', `${file} should be a PNG`);
    // PNG IHDR: width/height are big-endian uint32 at byte 16 / 20.
    assert.equal(buf.readUInt32BE(16), w, `${file} width`);
    assert.equal(buf.readUInt32BE(20), h, `${file} height`);
    assert.ok(buf.length > 20_000, `${file} looks empty`);
  }
});

test('PWA manifest keeps a relative scope so Pages subpaths work', () => {
  const manifest = JSON.parse(read('public/manifest.webmanifest'));
  assert.equal(manifest.start_url, './');
  assert.equal(manifest.scope, './');
  assert.equal(manifest.display, 'standalone');
  assert.equal(manifest.icons.length, 2);
  for (const icon of manifest.icons) assert.ok(exists(path.join('public', icon.src)), `missing icon ${icon.src}`);
});

test('launch kit and release notes stay in sync with the download URL', () => {
  const notes = read('docs/RELEASE_NOTES_TEMPLATE.md');
  assert.ok(notes.includes('ZeeFlix-latest.apk'), 'release notes must name the attached APK');
  assert.ok(notes.includes('SHA256SUMS.txt'), 'release notes must mention the checksums');
  const kit = read('docs/LAUNCH_KIT.md');
  assert.ok(kit.includes('releases/latest/download/ZeeFlix-latest.apk'), 'launch kit needs the stable APK link');
  for (const channel of ['Show HN', 'r/AndroidApps', 'LinkedIn', 'Product Hunt']) {
    assert.ok(kit.includes(channel), `launch kit is missing the ${channel} section`);
  }
});
